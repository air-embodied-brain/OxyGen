"""Build src/data/paper-figures.ts from the raw ECCV / NeurIPS-submission results.

Raw results (paths relative to the experiment workspace):
  RTX 4090:        results/eccv_submission_raw/results_eccv/
  Jetson AGX Thor: results/eccv_submission_raw/results_eccv_jetson_pytorch/

Metrics follow OxyGen/experiments/analysis/aggregate_metrics.py: warmup frames
are excluded, action frequency = H * frames / total frame time, and language
throughput = mean over frames of tokens / frame time. Series follow
plot_tradeoff.py and compute_speedup_ablation.py: S = 10, continuous batching
with uniform arrivals at rate 1, ablation "ours" at k = 5, "no batching" is the
shared-KV setting, and the upper bound is shared KV at N = 5.

With --check-pdf (needs pymupdf), every value is also compared with the
camera-ready figures read by extract_paper_figures.py; the report is written
to scripts/data/raw_verification.json.

Usage: python build_figure_data.py <workspace> [--check-pdf]
"""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TS = HERE.parents[1] / "src" / "data" / "paper-figures.ts"
REPORT = HERE / "raw_verification.json"

H = 10
S = 10
NS = [5, 10, 15, 20, 30]
CONFIGS = ["libero", "droid", "aloha"]
DEVICES = {
    "rtx4090": "results/eccv_submission_raw/results_eccv",
    "thor": "results/eccv_submission_raw/results_eccv_jetson_pytorch",
}
SERIES = {
    "baseline": ("baseline", None, NS),
    "parallel": ("parallel_mps", None, NS),
    "k1": ("continuous_batching", 1, NS),
    "k5": ("continuous_batching", 5, NS),
    "k10": ("continuous_batching", 10, [10, 20, 30]),
}
ABLATION = {
    "baseline": ("baseline", None),
    "parallel": ("parallel_mps", None),
    "no_batching": ("shared_kv", None),
    "ours": ("continuous_batching", 5),
}


def metrics(path: Path) -> tuple[float, float]:
    frames = [f for f in json.loads(path.read_text())["frames"] if not f.get("is_warmup", False)]
    hz = H * len(frames) / sum(f["frame_ms"] for f in frames) * 1000
    tps = [f["total_tokens_this_frame"] / f["frame_ms"] * 1000 for f in frames if f["frame_ms"] > 0]
    return hz, sum(tps) / len(tps)


def raw_file(root: Path, setting: str, cfg: str, n: int, k: int | None) -> Path:
    base = root / setting / f"pi05_o2_{cfg}"
    return base / (f"denoise{S}_decode{n}.json" if k is None else f"denoise{S}_decode{n}_step{k}_uniform_1.json")


def build(ws: Path) -> dict:
    data = {"tradeoff": {}, "ablation": {}, "sources": {}}
    for dev, rel in DEVICES.items():
        root = ws / rel
        data["sources"][dev] = rel
        for cfg in CONFIGS:
            panel = {}
            for name, (setting, k, ns) in SERIES.items():
                panel[name] = [[n, *metrics(raw_file(root, setting, cfg, n, k))] for n in ns]
            data["tradeoff"].setdefault(cfg, {})[dev] = panel
        abl = {name: [metrics(raw_file(root, s, "libero", n, k))[0] for n in NS] for name, (s, k) in ABLATION.items()}
        abl["upperBound"] = metrics(raw_file(root, "shared_kv", "libero", 5, None))[0]
        data["ablation"][dev] = abl
    return data


def check_pdf(data: dict, ws: Path) -> dict:
    import extract_paper_figures as ex

    fig_dir = ws / "NeurIPS-2026---OxyGen" / "figures" / "experiments"
    report = {}
    for cfg in CONFIGS:
        panels = dict(zip(DEVICES, ex.tradeoff(fig_dir / f"tradeoff_pi05_o2_{cfg}.pdf")))
        for dev in DEVICES:
            worst = 0.0
            for name, points in data["tradeoff"][cfg][dev].items():
                for raw, fig in zip(points, panels[dev][name]):
                    worst = max(worst, abs(raw[1] - fig["hz"]), abs(raw[2] - fig["tps"]))
            report[f"tradeoff.{cfg}.{dev}"] = round(worst, 3)
    panels = dict(zip(DEVICES, ex.ablation(fig_dir / "combined_ablation_pi05_o2_libero.pdf")))
    for dev in DEVICES:
        raw = data["ablation"][dev]
        worst = max(abs(a - b["hz"]) for name in ABLATION for a, b in zip(raw[name], panels[dev][name]))
        worst = max(worst, abs(raw["upperBound"] - panels[dev]["upper_bound_hz"]))
        report[f"ablation.libero.{dev}"] = round(worst, 3)
    return report


def write_ts(data: dict) -> None:
    r = lambda v: round(v, 1)
    trade = {
        cfg: {dev: {name: [[n, r(hz), r(tps)] for n, hz, tps in pts] for name, pts in panel.items()}
              for dev, panel in devs.items()}
        for cfg, devs in data["tradeoff"].items()
    }
    abl = {dev: {k: [r(x) for x in v] if isinstance(v, list) else r(v) for k, v in a.items()}
           for dev, a in data["ablation"].items()}
    TS.write_text(
        "// π0.5 tradeoff and ablation values, generated by scripts/data/build_figure_data.py\n"
        "// from the raw ECCV / NeurIPS-submission results:\n"
        f"//   RTX 4090: {data['sources']['rtx4090']}\n"
        f"//   Jetson AGX Thor: {data['sources']['thor']}\n\n"
        "/** [N, action frequency (Hz), language throughput (tok/s)] */\n"
        "export type TradeoffPoint = [number, number, number];\n"
        'export type SeriesKey = "baseline" | "parallel" | "k1" | "k5" | "k10";\n\n'
        'export const tradeoff: Record<"libero" | "droid" | "aloha", Record<"rtx4090" | "thor", Record<SeriesKey, TradeoffPoint[]>>> = '
        f"{json.dumps(trade)};\n\n"
        "/** Action frequency (Hz) on LIBERO at k=5 for N = 5, 10, 15, 20, 30. */\n"
        f"export const ablationN = {json.dumps(NS)};\n"
        'export const ablation: Record<"rtx4090" | "thor", { baseline: number[]; parallel: number[]; no_batching: number[]; ours: number[]; upperBound: number }> = '
        f"{json.dumps(abl)};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("workspace", type=Path)
    parser.add_argument("--check-pdf", action="store_true")
    args = parser.parse_args()
    data = build(args.workspace)
    write_ts(data)
    if args.check_pdf:
        report = {"max_abs_diff_raw_vs_figure": check_pdf(data, args.workspace), "sources": data["sources"]}
        REPORT.write_text(json.dumps(report, indent=2) + "\n")
        print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
